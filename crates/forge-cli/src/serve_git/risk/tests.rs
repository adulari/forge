fn file_from(path: &str, kind: &str, diff: &str, skipped: usize) -> GitDiffFile {
    GitDiffFile {
        path: path.to_string(),
        kind: kind.to_string(),
        orig_path: None,
        binary: false,
        adds: 0,
        dels: 0,
        hunks: vec![GitDiffHunk {
            header: "@@ -1,3 +1,3 @@".to_string(),
            risk: LOOK,
            reason: String::new(),
            lines: diff.split('\n').map(str::to_string).collect(),
        }],
        skipped_lines: skipped,
        offset: 0,
        total_lines: 0,
    }
}

#[test]
fn classification_vectors() {
    let mut failures = Vec::new();
    for vector in VECTORS {
        let mut file = file_from(vector.path, vector.kind, vector.diff, 0);
        classify_file(&mut file);
        let hunk = &file.hunks[0];
        if hunk.risk != vector.risk || hunk.reason != vector.reason {
            failures.push(format!(
                "{}: got {} / {:?}, want {} / {:?}",
                vector.name, hunk.risk, hunk.reason, vector.risk, vector.reason
            ));
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}

#[test]
fn routine_hunks_of_hand_written_files_never_drop_code() {
    for vector in VECTORS.iter().filter(|v| v.risk == "routine") {
        if matches!(
            vector.reason,
            "lockfile churn" | "generated file" | "snapshot update"
        ) {
            continue;
        }
        let mut file = file_from(vector.path, vector.kind, vector.diff, 0);
        classify_file(&mut file);
        let norm = |p: char| -> Vec<String> {
            vector
                .diff
                .lines()
                .filter_map(|l| l.strip_prefix(p))
                .map(|l| l.trim().to_string())
                .filter(|l| !l.is_empty())
                .collect()
        };
        let (mut removed, mut added) = (norm('-'), norm('+'));
        removed.sort();
        added.sort();
        assert_eq!(removed, added, "{}", vector.name);
    }
}

#[test]
fn a_cut_short_diff_is_never_routine_unless_it_is_a_lockfile() {
    let mut file = file_from("src/a.rs", "modified", "+\n+", 10);
    classify_file(&mut file);
    assert_eq!(file.hunks[0].risk, LOOK);
    let mut lock = file_from("Cargo.lock", "modified", "-a\n+b", 10);
    classify_file(&mut lock);
    assert_eq!(lock.hunks[0].risk, ROUTINE);
}

#[test]
fn binary_files_need_a_look() {
    let mut file = file_from("logo.png", "modified", "", 0);
    file.binary = true;
    classify_file(&mut file);
    assert_eq!(file.hunks[0].risk, LOOK);
}
